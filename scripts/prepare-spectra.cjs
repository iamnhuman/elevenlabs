#!/usr/bin/env node
/* Measured short-time Fourier transforms, synchronized by audio.currentTime.
   Generation only: Node.js + ffmpeg. The published site has no build step. */
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const catalogue = JSON.parse(fs.readFileSync(path.join(root, 'samples.js'), 'utf8').split('window.SAMPLE_LIBRARY = ')[1].replace(/;\s*$/, ''));
const BINS = 256, RATE = 96, SAMPLE_RATE = 32000, SIZE = 4096;
const MIN_DB = -96, MAX_DB = -12;
const output = path.join(root, 'assets', 'spectrum');
fs.mkdirSync(output, { recursive: true });
const reverse = new Uint16Array(SIZE), hann = new Float64Array(SIZE);
const bits = Math.log2(SIZE);
for (let i = 0; i < SIZE; i++) {
  let n = i, r = 0;
  for (let bit = 0; bit < bits; bit++) { r = (r << 1) | (n & 1); n >>= 1; }
  reverse[i] = r;
  hann[i] = .5 - .5 * Math.cos(2 * Math.PI * i / (SIZE - 1));
}
const frequencies = Array.from({ length: BINS }, (_, i) => 32 * 500 ** (i / (BINS - 1)));
const halfBand = 500 ** (1 / (2 * (BINS - 1)));
const ranges = frequencies.map(freq => [
  Math.max(1, Math.floor(freq / halfBand * SIZE / SAMPLE_RATE)),
  Math.min(SIZE / 2, Math.max(1, Math.ceil(freq * halfBand * SIZE / SAMPLE_RATE))),
]);
const manifest = { version: 2, bins: BINS, rate: RATE, fftSize: SIZE, sampleRate: SAMPLE_RATE, minFreq: 32, maxFreq: 16000, minDb: MIN_DB, maxDb: MAX_DB, samples: [] };
for (const sample of catalogue.samples) {
  const input = path.join(root, decodeURIComponent(sample.src));
  const file = `${sample.id}.js`, target = path.join(output, file);
  const frames = Math.ceil(sample.duration * RATE);
  if (!fs.existsSync(target) || fs.statSync(target).mtimeMs < Math.max(fs.statSync(input).mtimeMs, fs.statSync(__filename).mtimeMs)) {
    const decoded = spawnSync('ffmpeg', ['-v', 'error', '-i', input, '-vn', '-ac', '1', '-ar', String(SAMPLE_RATE), '-f', 'f32le', '-'], { maxBuffer: 64 * 1024 * 1024 });
    if (decoded.status !== 0) throw new Error(decoded.stderr.toString());
    const pcm = new Float32Array(decoded.stdout.buffer, decoded.stdout.byteOffset, decoded.stdout.byteLength / 4);
    const values = Buffer.alloc(frames * BINS), re = new Float64Array(SIZE), im = new Float64Array(SIZE);
    const power = new Float64Array(SIZE / 2 + 1);
    for (let frame = 0; frame < frames; frame++) {
      const start = Math.floor(frame / RATE * SAMPLE_RATE) - SIZE / 2;
      for (let i = 0; i < SIZE; i++) { re[reverse[i]] = (pcm[start + i] || 0) * hann[i]; im[i] = 0; }
      for (let length = 2; length <= SIZE; length *= 2) {
        const angle = -2 * Math.PI / length, cos = Math.cos(angle), sin = Math.sin(angle), half = length / 2;
        for (let i = 0; i < SIZE; i += length) {
          let wr = 1, wi = 0;
          for (let j = 0; j < half; j++) {
            const a = i + j, b = a + half;
            const tr = wr * re[b] - wi * im[b], ti = wr * im[b] + wi * re[b];
            re[b] = re[a] - tr; im[b] = im[a] - ti; re[a] += tr; im[a] += ti;
            const next = wr * cos - wi * sin; wi = wr * sin + wi * cos; wr = next;
          }
        }
      }
      for (let i = 0; i < power.length; i++) power[i] = re[i] * re[i] + im[i] * im[i];
      for (let bin = 0; bin < BINS; bin++) {
        let peak = 0;
        for (let i = ranges[bin][0]; i <= ranges[bin][1]; i++) peak = Math.max(peak, power[i]);
        const db = 10 * Math.log10(Math.max(1e-20, peak * 16 / (SIZE * SIZE)));
        values[frame * BINS + bin] = Math.round(Math.max(0, Math.min(1, (db - MIN_DB) / (MAX_DB - MIN_DB))) * 255);
      }
    }
    const entry = { version: 2, bins: BINS, rate: RATE, frames, minDb: MIN_DB, maxDb: MAX_DB, values: values.toString('base64') };
    fs.writeFileSync(target, `// Measured FFT from ${sample.id}.mp3; generated by scripts/prepare-spectra.cjs.\nwindow.SAMPLE_SPECTRA ||= {};\nwindow.SAMPLE_SPECTRA[${JSON.stringify(sample.id)}] = ${JSON.stringify(entry)};\n`);
  }
  manifest.samples.push({ id: sample.id, file: `assets/spectrum/${file}`, frames, bytes: fs.statSync(target).size });
  if (manifest.samples.length % 20 === 0) console.log(`Measured ${manifest.samples.length}/${catalogue.samples.length} spectra…`);
}
fs.writeFileSync(path.join(output, 'manifest.json'), JSON.stringify(manifest));
console.log(`Prepared ${manifest.samples.length} measured FFT histories, ${BINS} logarithmic bands, ${RATE} frames/s, ${(manifest.samples.reduce((n, s) => n + s.bytes, 0) / 1e6).toFixed(2)} MB. Audio files unchanged.`);
