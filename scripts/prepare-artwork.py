#!/usr/bin/env python3
"""Package generated macro atlases without editing their photographic content.

Requires cwebp. Original PNGs stay intact; precise square crops are CSS metadata.
"""
import json
from pathlib import Path
import shutil
import struct
import subprocess

ROOT = Path(__file__).resolve().parent.parent
ART = ROOT / "assets/art/macro-200"


def main():
    encoder = shutil.which("cwebp")
    if not encoder:
        raise SystemExit("Install cwebp before preparing the image assets.")
    layout = json.loads((ART / "layout.json").read_text())
    sheets, cells = [], []
    for index, spec in enumerate(layout):
        stem = f"atlas-{index + 1:02d}"
        source, target = ART / f"{stem}.png", ART / f"{stem}.webp"
        width, height = struct.unpack(">II", source.read_bytes()[16:24])
        assert width == height == spec["width"] == spec["height"]
        if not target.exists() or target.stat().st_mtime < source.stat().st_mtime:
            subprocess.run([encoder, "-quiet", "-q", "88", "-m", "6", str(source), "-o", str(target)], check=True)
        sheets.append({"file": target.relative_to(ROOT).as_posix(),
                       "source": source.relative_to(ROOT).as_posix(),
                       "width": width, "height": height})
        group = []
        for row in range(5):
            for column in range(5):
                left, right = spec["x"][column:column + 2]
                top, bottom = spec["y"][row:row + 2]
                # Generative contact sheets have small alignment variations.
                # Inscribe a square and inset it to keep all grid lines outside.
                side = min(right - left, bottom - top) - 8
                x, y = left + (right - left - side) / 2, top + (bottom - top - side) / 2
                group.append({"sheet": index, "x": x, "y": y, "size": side})
        cells.append(group)
    # Alternate subjects across neighboring cards while keeping 200 fixed slots.
    cards = [cells[sheet][cell] for cell in range(25) for sheet in range(8)]
    catalogue = {"count": len(cards), "columns": 5, "rows": 5,
                 "sheets": sheets, "cards": cards}
    (ART / "manifest.json").write_text(json.dumps(catalogue, indent=2) + "\n")
    (ART / "artwork.js").write_text("// Generated by scripts/prepare-artwork.py.\nwindow.SAMPLE_ART = "
                                    + json.dumps(catalogue, separators=(",", ":")) + ";\n")
    print(f"Prepared {len(cards)} unique card slots in {len(sheets)} WebP atlases; "
          f"{sum((ROOT / s['file']).stat().st_size for s in sheets) / 1e6:.2f} MB total.")


if __name__ == "__main__":
    main()
